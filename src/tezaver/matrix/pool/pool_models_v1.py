"""
Pool Models V1
==============

Data models for the Matrix Pool Engine (Phase 2A).
Includes Universe, Tick, and Intent definitions.
"""
from dataclasses import dataclass, field
from typing import List, Dict, Optional, Any

@dataclass
class PoolUniverseCellV1:
    """Represents a single executable cell (symbol+timeframe) in the pool universe."""
    symbol: str
    timeframe: str
    bundles_loaded_ok: List[str]  # List of bundle_ids
    best_bundle_id: Optional[str] = None
    qc_score_best: Optional[int] = None
    tier_best: Optional[str] = None

@dataclass
class PoolUniverseReportV1:
    """Report generated after building the pool universe."""
    run_id: str
    stage: str
    engine_version: str
    data_fingerprint: str
    config_signature: str
    built_ts_iso: str
    cells_total: int
    cells_by_tf: Dict[str, int]
    cells: List[PoolUniverseCellV1]
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "run_id": self.run_id,
            "stage": self.stage,
            "engine_version": self.engine_version,
            "data_fingerprint": self.data_fingerprint,
            "config_signature": self.config_signature,
            "built_ts_iso": self.built_ts_iso,
            "cells_total": self.cells_total,
            "cells_by_tf": self.cells_by_tf,
            "cells": [
                {
                    "symbol": c.symbol,
                    "timeframe": c.timeframe,
                    "bundles_loaded_ok": c.bundles_loaded_ok,
                    "best_bundle_id": c.best_bundle_id,
                    "qc_score_best": c.qc_score_best,
                    "tier_best": c.tier_best
                } for c in self.cells
            ]
        }

@dataclass
class PoolTickReportV1:
    """Report generated for each pool engine tick."""
    run_id: str
    stage: str
    engine_version: str
    data_fingerprint: str
    config_signature: str
    tick_ts_iso: str
    tick_reason: str # e.g. "BAR_CLOSED"
    closed_bars: Dict[str, str] # timeframe -> bar_ts_iso
    intents_considered: int
    intents_created: int
    intents_skipped: int
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "run_id": self.run_id,
            "stage": self.stage,
            "engine_version": self.engine_version,
            "data_fingerprint": self.data_fingerprint,
            "config_signature": self.config_signature,
            "tick_ts_iso": self.tick_ts_iso,
            "tick_reason": self.tick_reason,
            "closed_bars": self.closed_bars,
            "intents_considered": self.intents_considered,
            "intents_created": self.intents_created,
            "intents_skipped": self.intents_skipped
        }

@dataclass
class TradeIntentV1:
    """Deterministic trade intent generated by the pool engine."""
    intent_id: str
    symbol: str
    timeframe: str
    bundle_id: str
    trigger_type: str
    exit_policy: str
    created_ts_iso: str
    reason: str # "OK", "SKIPPED_..."
    qc_score: int
    tier: Optional[str] = None
    entry_ts_iso: Optional[str] = None
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "intent_id": self.intent_id,
            "symbol": self.symbol,
            "timeframe": self.timeframe,
            "bundle_id": self.bundle_id,
            "trigger_type": self.trigger_type,
            "exit_policy": self.exit_policy,
            "created_ts_iso": self.created_ts_iso,
            "reason": self.reason,
            "qc_score": self.qc_score,
            "tier": self.tier,
            "entry_ts_iso": self.entry_ts_iso
        }

@dataclass
class PoolIntentsReportV1:
    """Report containing all generated intents for a tick/run."""
    run_id: str
    stage: str
    engine_version: str
    data_fingerprint: str
    config_signature: str
    built_ts_iso: str
    intents_total: int
    intents_created: int
    intents_skipped: int
    intents: List[TradeIntentV1]
    skipped_reasons_count: Dict[str, int]
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "run_id": self.run_id,
            "stage": self.stage,
            "engine_version": self.engine_version,
            "data_fingerprint": self.data_fingerprint,
            "config_signature": self.config_signature,
            "built_ts_iso": self.built_ts_iso,
            "intents_total": self.intents_total,
            "intents_created": self.intents_created,
            "intents_skipped": self.intents_skipped,
            "intents": [i.to_dict() for i in self.intents],
            "skipped_reasons_count": self.skipped_reasons_count
        }
